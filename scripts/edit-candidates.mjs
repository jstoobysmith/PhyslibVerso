#!/usr/bin/env node
/*
 * Build edit-candidates.json: wiki pages that would most benefit from more
 * documentation, for the "help wanted" table on the home page.
 *
 *   node scripts/edit-candidates.mjs [--data <roadmap-data.json>] [--out <file>]
 *
 * Metric: **declarations per docstring character**. A page with many formalized
 * results but a short module docstring (overview) is under-documented and a good
 * target for a first edit. score = declarations · 100 / (docstring length + 1);
 * higher = more content, less prose. Only formalized modules (Physlib /
 * PhyslibAlpha, which have wiki pages) with ≥ 3 declarations are considered.
 *
 * Reads the already-generated roadmap-data.json (which carries each file's
 * docstring and declaration list), so it stays DRY with the roadmap build.
 *
 * Requires Node 18+. No dependencies.
 */

import { readFile, writeFile } from 'node:fs/promises';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const REPO = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const args = process.argv.slice(2);
const opt = (name, fallback) => {
  const i = args.indexOf(name);
  return i >= 0 && args[i + 1] ? args[i + 1] : fallback;
};
const DATA = path.resolve(opt('--data', path.join(REPO, 'roadmap-data.json')));
const OUT = path.resolve(opt('--out', path.join(REPO, 'edit-candidates.json')));
const LIMIT = Number(opt('--limit', '40'));

const data = JSON.parse(await readFile(DATA, 'utf8').catch((err) => {
  console.error(`Cannot read ${DATA}: ${err.message}\nRun scripts/roadmap-data.mjs first, or pass --data.`);
  process.exit(1);
}));

function* walk(node) {
  yield node;
  for (const c of node.children || []) yield* walk(c);
}

const candidates = [];
for (const node of walk(data.tree)) {
  const decls = node.decls;
  if (!decls || !node.sources) continue;
  // Only formalized modules that actually have a wiki page.
  const formalized = node.sources.includes('Physlib') || node.sources.includes('PhyslibAlpha');
  if (!formalized || !node.moduleHref) continue;
  const declCount = decls.filter((d) => d.source !== 'UnformalizedClaims').length;
  if (declCount < 3) continue;
  const docChars = (node.doc || '').length;
  candidates.push({
    path: node.path,
    name: node.name,
    href: node.moduleHref.replace(/^\.\.\//, ""),
    source: node.sources.includes('Physlib') ? 'Physlib' : 'PhyslibAlpha',
    decls: declCount,
    docChars,
    score: declCount * 100 / (docChars + 1),
  });
}

/* Two per top-level area of Physlib (the first path segment), each area's most
   under-documented pages, then ordered by area name for a tidy table. */
const PER_AREA = Number(opt('--per-area', '2'));
const byArea = new Map();
for (const c of candidates.sort((a, b) => b.score - a.score || b.decls - a.decls)) {
  const area = c.path.split('.')[0];
  const list = byArea.get(area) || [];
  if (list.length < PER_AREA) { list.push(c); byArea.set(area, list); }
}
const top = [...byArea.keys()].sort((a, b) => a.localeCompare(b, 'en'))
  .flatMap((area) => byArea.get(area))
  .map(({ score, ...rest }) => rest);

const output = {
  note: 'Generated by scripts/edit-candidates.mjs — two least-documented pages per Physlib area.',
  metric: 'declarations per docstring character (higher = more content, less documentation)',
  perArea: PER_AREA,
  count: top.length,
  candidates: top,
};

await writeFile(OUT, JSON.stringify(output) + '\n');
console.error(`Wrote ${path.relative(REPO, OUT)} — ${top.length} candidates (of ${candidates.length} eligible pages)`);
